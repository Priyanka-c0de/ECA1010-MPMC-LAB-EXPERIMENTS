
ORG 100H

; Install NMI vector (INT 02H)
MOV AX, CS
MOV BX, AX
MOV AX, 0000H
MOV ES, AX

MOV WORD PTR ES:[0008H], OFFSET ISR
MOV WORD PTR ES:[000AH], BX

MOV SP, 0FFEH

; Clear event count
MOV BYTE PTR [2900H], 00H

; Simulate 4 interrupt events
MOV AL, 11H
MOV [2905H], AL
INT 02H

MOV AL, 22H
MOV [2905H], AL
INT 02H

MOV AL, 33H
MOV [2905H], AL
INT 02H

MOV AL, 44H
MOV [2905H], AL
INT 02H

HLT

; NMI Service Routine
ISR:
PUSH AX
PUSH BX
PUSH DX

MOV BL, [2900H]
MOV BH, 00H

MOV AL, [2905H]
MOV [BX+2901H], AL

INC BYTE PTR [2900H]

POP DX
POP BX
POP AX

IRET
